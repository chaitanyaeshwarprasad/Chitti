"""Render Chitti's body animations (docs/design/anim.html) and pack them for the board's 'anim' partition.

python tools_anim.py            -> build/anim/*.png sheets, anim.bin, main/anim_ids.h

anim.bin layout (little-endian):
  header : 'CHAN' u16 n_anims u16 n_frames
  anims  : n_anims x { char name[12]; u16 first; u16 count; u8 fps; u8 loop; u16 pad }
  frames : n_frames x { u32 offset; u32 size; i16 x0, y0; u16 w, h; i16 hx10, hy10, jx10, jy10 }
  data   : per frame: 256 x u16 palette (RGB565, panel byte order) + RLE of palette indices (w*h)
           RLE control byte c: c & 0x80 -> run of (c & 0x7F) + 1 copies of the next byte
                               else     -> (c + 1) literal bytes follow
"""
import html
import json
import re
import struct
import subprocess
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent
PAGE = ROOT.parent / "docs" / "design" / "anim.html"
OUT = ROOT / "build_anim"
EDGE = r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"
NAMES = ["idle", "wave", "angry", "laugh", "think", "talk", "dance", "leave", "enter", "sleep",
         "happy", "sad", "surprised", "playful", "yawn", "drive", "carleave", "carenter"]
CELL = 466


def edge(*args):
    return subprocess.run([EDGE, "--headless=new", "--disable-gpu", "--hide-scrollbars",
                           "--force-device-scale-factor=1", *args], capture_output=True, text=True, timeout=120)


def render(name):
    url = PAGE.as_uri() + "#" + name
    dom = edge("--virtual-time-budget=3000", "--dump-dom", url).stdout
    meta = json.loads(html.unescape(re.search(r'<pre id="meta">(.*?)</pre>', dom, re.S).group(1)))
    cols = min(meta["n"], meta["cols"])
    rows = (meta["n"] + meta["cols"] - 1) // meta["cols"]
    png = OUT / f"{name}.png"
    edge(f"--window-size={cols * CELL},{rows * CELL}", f"--screenshot={png}", url)
    return meta, Image.open(png).convert("RGB")


def rgb565_be(r, g, b):
    v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return struct.pack(">H", v)


def rle(data: bytes) -> bytes:
    out, i, n = bytearray(), 0, len(data)
    while i < n:
        j = i
        while j < n and j - i < 128 and data[j] == data[i]:
            j += 1
        if j - i >= 3:
            out += bytes((0x80 | (j - i - 1), data[i]))
            i = j
            continue
        j = i
        while j < n and j - i < 128 and not (j + 2 < n and data[j] == data[j + 1] == data[j + 2]):
            j += 1
        out += bytes((j - i - 1,)) + data[i:j]
        i = j
    return bytes(out)


def encode_frame(img: Image.Image):
    mask = img.convert("L").point(lambda v: 255 if v > 6 else 0)
    box = mask.getbbox() or (0, 0, 2, 2)
    x0, y0 = box[0] & ~1, box[1] & ~1
    x1, y1 = min(CELL, (box[2] + 1) & ~1), min(CELL, (box[3] + 1) & ~1)
    crop = img.crop((x0, y0, x1, y1))
    q = crop.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:768] + [0] * (768 - len(q.getpalette()[:768]))
    palette = b"".join(rgb565_be(pal[k * 3], pal[k * 3 + 1], pal[k * 3 + 2]) for k in range(256))
    return x0, y0, x1 - x0, y1 - y0, palette + rle(q.tobytes())


def main():
    OUT.mkdir(exist_ok=True)
    anims, frames, blobs = [], [], []
    for name in NAMES:
        meta, sheet = render(name)
        first = len(frames)
        for f in range(meta["n"]):
            cx, cy = (f % meta["cols"]) * CELL, (f // meta["cols"]) * CELL
            x0, y0, w, h, blob = encode_frame(sheet.crop((cx, cy, cx + CELL, cy + CELL)))
            m = meta["frames"][f]
            frames.append((x0, y0, w, h, round(m["hx"] * 10), round(m["hy"] * 10), round(m["jx"] * 10), round(m["jy"] * 10)))
            blobs.append(blob)
        anims.append((name, first, meta["n"], meta["fps"], meta["loop"]))
        print(f"{name:6s} {meta['n']:2d} frames, {sum(len(b) for b in blobs[first:]) // 1024} KB")

    head = b"CHAN" + struct.pack("<HH", len(anims), len(frames))
    table = b"".join(struct.pack("<12sHHBBH", n.encode(), f0, c, fps, lp, 0) for n, f0, c, fps, lp in anims)
    off = len(head) + len(table) + len(frames) * 24
    ftab, data = b"", b""
    for fr, blob in zip(frames, blobs):
        ftab += struct.pack("<IIhhHHhhhh", off + len(data), len(blob), *fr)
        data += blob
    out = head + table + ftab + data
    (ROOT / "anim.bin").write_bytes(out)
    ids = "\n".join(f"#define ANIM_{n.upper()} {i}" for i, (n, *_r) in enumerate(anims))
    (ROOT / "main" / "anim_ids.h").write_text(f"// Generated by tools_anim.py\n#pragma once\n{ids}\n#define ANIM_COUNT {len(anims)}\n")
    print(f"anim.bin {len(out) / 1024 / 1024:.2f} MB, {len(frames)} frames")


if __name__ == "__main__":
    main()
